import { useState, useMemo } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import ProjectCard from './ProjectCard'
import ScrollReveal from './ScrollReveal'
import { useLanguage } from '../context/LanguageContext'

const ProjectGrid = ({ activeCategory = 'motion', onCategoryChange }) => {
    const { t } = useLanguage()
    const activeFilter = activeCategory
    const [isTransitioning, setIsTransitioning] = useState(false)

    const filters = [
        { id: 'motion', label: t.categories.motion },
        { id: 'short_form', label: t.categories.short_form }
    ]

    const filteredProjects = useMemo(() => {
        return PROJECTS.filter(p => p.subcategory === activeFilter)
    }, [activeFilter])

    const handleFilterChange = (filterId) => {
        if (filterId !== activeFilter) {
            setIsTransitioning(true)
            onCategoryChange?.(filterId)
            // Reset transition state after animation completes
            setTimeout(() => setIsTransitioning(false), 400)
        }
    }

    return (
        <section id="work" className="scroll-mt-48 pt-20 pb-32">
            <ScrollReveal width="100%">
                <div className="flex flex-col md:flex-row justify-between items-start md:items-end mb-16 gap-8">
                    <div>
                        <h2 className="text-3xl md:text-5xl font-bold tracking-tighter uppercase text-black dark:text-white mb-4 transition-colors duration-500">
                            {t.work.title}
                        </h2>
                        <p className="text-gray-500 dark:text-gray-400 text-sm tracking-[0.2em] uppercase font-light transition-colors duration-500">
                            {t.work.subtitle}
                        </p>
                    </div>

                    {/* Filter Bar */}
                    <div className="flex flex-wrap gap-4 md:gap-8">
                        {filters.map((filter) => (
                            <motion.button
                                key={filter.id}
                                onClick={() => handleFilterChange(filter.id)}
                                className={`text-[10px] font-bold tracking-[0.3em] uppercase relative pb-1
                                    ${activeFilter === filter.id
                                        ? 'text-[#f97316]'
                                        : 'text-gray-400 hover:text-black dark:hover:text-white'}`}
                                whileHover={{ scale: 1.05, y: -2 }}
                                whileTap={{ scale: 0.95 }}
                                transition={{ type: "spring", stiffness: 400, damping: 17 }}
                            >
                                {filter.label}
                                {activeFilter === filter.id && (
                                    <motion.div
                                        layoutId="activeFilter"
                                        className="absolute bottom-0 left-0 right-0 h-0.5 bg-[#f97316]"
                                        transition={{
                                            type: "spring",
                                            stiffness: 380,
                                            damping: 30
                                        }}
                                    />
                                )}
                            </motion.button>
                        ))}
                    </div>
                </div>
            </ScrollReveal>

            {/* Standard layout for filtered views */}
            <div className="relative">
                {/* Loading Overlay */}
                <AnimatePresence>
                    {isTransitioning && (
                        <motion.div
                            initial={{ opacity: 0 }}
                            animate={{ opacity: 1 }}
                            exit={{ opacity: 0 }}
                            className="absolute inset-0 bg-white/50 dark:bg-black/50 backdrop-blur-[2px] z-10 flex items-center justify-center pointer-events-none"
                        >
                            <motion.div
                                animate={{ rotate: 360 }}
                                transition={{ duration: 1, repeat: Infinity, ease: "linear" }}
                                className="w-8 h-8 border-2 border-[#f97316] border-t-transparent rounded-full"
                            />
                        </motion.div>
                    )}
                </AnimatePresence>

                <motion.div
                    layout
                    className={`grid gap-y-16 gap-x-6 sm:gap-x-10
                        ${activeFilter === 'short_form'
                            ? 'grid-cols-2 md:grid-cols-3 lg:grid-cols-5'
                            : 'grid-cols-1 md:grid-cols-2 lg:grid-cols-3'}`}
                    transition={{
                        layout: {
                            type: "spring",
                            stiffness: 300,
                            damping: 30
                        }
                    }}
                >
                    <AnimatePresence mode="popLayout">
                        {filteredProjects.map((project, index) => {
                            const isShortForm = project.subcategory === 'short_form'
                            return (
                                <motion.div
                                    key={project.id}
                                    layout
                                    initial={{ opacity: 0, scale: 0.8, y: 20 }}
                                    animate={{ opacity: 1, scale: 1, y: 0 }}
                                    exit={{ opacity: 0, scale: 0.8, y: -20 }}
                                    transition={{
                                        duration: 0.4,
                                        delay: index * 0.03,
                                        type: "spring",
                                        stiffness: 300,
                                        damping: 25
                                    }}
                                >
                                    <ProjectCard
                                        {...project}
                                        aspectRatio={isShortForm ? 'aspect-[9/16]' : 'aspect-[4/3]'}
                                        compact={isShortForm}
                                    />
                                </motion.div>
                            )
                        })}
                    </AnimatePresence>
                </motion.div>
            </div>
        </section>
    )
}

